use serde::{Deserialize, Serialize};
use std::fmt;

/// Maximum UTF-8 byte length of an OIDC-owned serialized authorization envelope.
pub const OIDC_CONTINUATION_CONTEXT_MAX_BYTES: usize = 64 * 1024;

/// Pending protocol context, NOT authentication authority or an authorization code.
///
/// qid-oidc must serialize an already validated, versioned authorization envelope
/// (including resolved PAR/JAR context), without transient DPoP proofs. Storage
/// checks only its JSON-object shape and size, not its protocol semantics.
#[derive(Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct OidcAuthorizationContinuation {
    /// Opaque, unpredictable transaction ID generated by qid-oidc.
    pub id: String,
    pub realm_id: String,
    pub user_id: String,
    pub client_id: String,
    pub context_json: String,
    /// SHA-256 of the browser-held binding secret; never store the raw secret.
    pub browser_binding_sha256: [u8; 32],
    /// Unix seconds from the trusted server clock, never request timestamps.
    pub created_at: u64,
    pub expires_at: u64,
}

impl fmt::Debug for OidcAuthorizationContinuation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("OidcAuthorizationContinuation")
            .field("id", &self.id)
            .field("realm_id", &self.realm_id)
            .field("user_id", &self.user_id)
            .field("client_id", &self.client_id)
            .field("created_at", &self.created_at)
            .field("expires_at", &self.expires_at)
            .finish_non_exhaustive()
    }
}
